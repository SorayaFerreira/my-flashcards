// The release key and its passwords never enter git: android/key.properties (gitignored)
// points to the keystore in ~/.android-keys/. Without that file the "release" signing
// config stays incomplete, so only release builds fail; debug builds keep working.
val keystoreProperties = Properties()
val keystorePropertiesFile = rootProject.file("key.properties")
if (keystorePropertiesFile.exists()) {
    keystorePropertiesFile.inputStream().use { keystoreProperties.load(it) }
}

